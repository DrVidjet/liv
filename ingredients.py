def snack_portion(name):
    """(граммы, [ккал, б, ж, у]) на порцию или None."""
    value = words(name)
    for pattern, grams, per100 in _SNACK_VALUES:
        if re.search(r"\b(?:" + pattern + ")", value):
            return grams, [round(v * grams / 100, 1) for v in per100]
    return None
