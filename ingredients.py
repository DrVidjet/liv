"""Сопоставление продуктов «что есть дома» с ингредиентами рецептов Food.ru."""
import re


def words(value):
    return re.sub(r"[^а-яa-z0-9]+", " ", value.lower().replace("ё", "е")).strip()


# --- исключения (яйца и производные) ---------------------------------------

def has_egg(name):
    value = words(name)
    return bool(re.search(r"\b(?:яйц|яиц|яич|желто[кч]|желтк|меланж|майонез|безе|меренг|альбумин|омлет|глазунь)", value)
                or value in {"белок", "белки"} or re.search(r"(?:курин|перепелин)\w* бел", value))


def excludes(name, ingredient):
    if has_egg(ingredient):
        return has_egg(name)
    return " "+words(ingredient)+" " in " "+words(name)+" "


def egg_dish(title):
    """Блюдо, где яйца — главное: омлет, яичница, яйца пашот, салат с яйцом… (не тесто и не панировка)."""
    value = re.sub(r"\bбез (?:яиц|яйц\w*)", " ", words(title))
    return bool(re.search(r"\b(?:омлет|яичниц|глазун|скрэмбл|пашот|бенедикт|фриттат|шакшук|яйц|яиц|яичн|желтк|безе|меренг|гоголь)",
                          value))


def dish_of(title, restriction):
    """Исключение «только блюда из него»: продукт в названии блюда."""
    if has_egg(restriction):
        return egg_dish(title)
    return excludes(title, restriction)


# --- сопоставление -----------------------------------------------------------

_ENDINGS = sorted("""ями ами ого его ому ему ыми ими ая яя ое ее ые ие ой ей ий ый ую юю ом ем ах ях ов ев
                     ка ки ку ок а я о е ы и у ю ь й""".split(), key=len, reverse=True)


def stem(word):
    for ending in _ENDINGS:
        if word.endswith(ending) and len(word) - len(ending) >= 3:
            return word[:-len(ending)]
    return word


# Уточняющие слова, которые не меняют сам продукт
_NOISE = {"свеж", "молод", "красн", "бел", "желт", "крупн", "мелк", "средн", "охлажден", "замороженн", "отварн",
          "очищенн", "нарезанн", "домашн", "натуральн", "жирност", "рафинированн", "нерафинированн", "extra",
          "virgin", "морожен", "свежеморожен", "бэби", "беби", "мини", "хлебопекарн", "высш", "сорт", "кипят", "питьев", "фильтрованн"}


def stems(name):
    return {stem(w) for w in words(name).split() if not w.isdigit() and stem(w) not in _NOISE}


# Группы, где названия у Food.ru и в жизни заметно расходятся (None — сравниваем по словам)
_GROUPS = [
    ("яйца", r"\b(?:яйц|яиц)"),
    ("мороженое", r"\bмороженое\b|\bпломбир"),
    (None, r"\b(?:сосиск|сардельк|колбас|ветчин|бекон|наггетс|бульонн\w* кубик)"),
    (None, r"(?:гречнев|кукурузн|рисов|пшеничн)\w* хлопь|хлопь\w* (?:гречнев|кукурузн|рисов|пшеничн)|гречнев\w* лапш|лапш\w* гречнев|соба\b"),
    ("курица", r"\b(?:кур(?:иц|ин|оч|ятин)|цыпл|бройлер)"),
    ("картофель", r"\bкартоф|\bкартош"),
    ("помидор", r"\bпомидор|\bтомат(?:ы|ов)?\b|\bчерри\b"),
    ("огурец", r"\bогур"),
    ("кабачок", r"\bкабач|\bцукини"),
    ("болгарский перец", r"\bболгарск|\bсладк\w* перец|\bперец сладк"),
    ("макароны", r"\bмакарон|\bспагетти|\bвермишел|\bпенне|\bфузилли|\bфарфалле|\bтальятелле|\bлапш"),
    ("говядина", r"\bговя|\bтелят"),
    ("свинина", r"\bсвин"),
    ("индейка", r"\bиндей|\bиндюш"),
    ("фарш", r"\bфарш"),
    ("рис", r"\bрис\b|\bрис (?:белый|бурый|длиннозерн|круглозерн)|\bбасмати|\bжасмин"),
    ("гречка", r"\bгреч"),
    ("овсянка", r"\bовсян|\bгеркулес"),
    ("творог", r"\bтворог|\bтворож(?:ок|н\w* масс)"),
    (None, r"(?:цветн|брокк|пекин|кольраб|брюссел|морск|китайск)\w* капуст|капуста (?:брокк|кольраб|романеско)"),
    ("капуста", r"\bкапуст"),
    (None, r"(?:сгущ|кокос|миндал|соев|овсян|рисов|сух|топлен)\w* молок"),
    ("молоко", r"\bмолок[оау]?\b"),
    ("чеснок", r"\bчеснок"),
    ("лук", r"(?:^|\s)лук(?:\s|$)(?!.*зелен)"),
]


def group(name):
    value = words(name)
    if re.search(r"\b(?:перепелин)", value):
        return None
    for key, pattern in _GROUPS:
        if re.search(pattern, value):
            return key
    return None


def covers(have, ingredient):
    """Продукт из списка «что есть» закрывает ингредиент рецепта."""
    g = group(ingredient)
    if g:
        return group(have) == g
    if group(have):
        return False
    hs, ings = stems(have), stems(ingredient)
    return bool(hs) and hs <= ings


